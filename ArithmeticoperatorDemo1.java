package com.demo1;

public class ArithmeticoperatorDemo1 {
    static void main() {
        //+
        System.out.println(3 + 2);
        //-
        System.out.println(5 - 1);
        //*
        System.out.println(7 * 8);

        //在代码中,如果有销售
        System.out.println(1.1 + 1.01);
        System.out.println(1.1 - 1.01);
        System.out.println(1.1 * 1.03);
    }
}
